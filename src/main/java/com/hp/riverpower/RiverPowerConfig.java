package com.hp.riverpower;

import com.simibubi.create.api.registry.SimpleRegistry;
import com.simibubi.create.api.stress.BlockStressValues;
import net.minecraft.world.level.block.Block;
import net.neoforged.neoforge.common.ModConfigSpec;
import net.neoforged.fml.config.ModConfig;
import net.neoforged.fml.ModContainer;

public final class RiverPowerConfig {
    public static final WheelConfig ANDESITE = new WheelConfig("andesite_large_water_wheel", "安山大水车", "Andesite Large Water Wheel", 4, 2.0, "安山机壳", "Andesite Casing");
    public static final WheelConfig BRASS = new WheelConfig("brass_large_water_wheel", "黄铜大水车", "Brass Large Water Wheel", 4, 3.0, "黄铜机壳", "Brass Casing");
    public static final WheelConfig STURDY = new WheelConfig("sturdy_large_water_wheel", "坚固板大水车", "Sturdy Large Water Wheel", 4, 4.0, "坚固板", "Sturdy Sheet");

    private RiverPowerConfig() {
    }

    public static void register(ModContainer container) {
        for (WheelConfig wheel : new WheelConfig[] {ANDESITE, BRASS, STURDY}) {
            container.registerConfig(ModConfig.Type.COMMON, wheel.spec, "riverpower-" + wheel.name + ".toml");
        }
    }

    public static final class WheelConfig {
        public final String name;
        public final ModConfigSpec spec;
        private final int defaultRpm;
        private final double defaultMultiplier;
        private final ModConfigSpec.IntValue rpm;
        private final ModConfigSpec.DoubleValue stressMultiplier;
        private final ModConfigSpec.BooleanValue upgradeEnabled;

        private WheelConfig(String name, String nameZh, String nameEn, int defaultRpm, double defaultMultiplier,
                            String itemZh, String itemEn) {
            this.name = name;
            this.defaultRpm = defaultRpm;
            this.defaultMultiplier = defaultMultiplier;
            ModConfigSpec.Builder builder = new ModConfigSpec.Builder();
            builder.comment(
                    nameZh + " 配置文件",
                    nameEn + " configuration").push("wheel");
            rpm = builder.comment(
                    "水车在有水流时输出的转速（RPM），修改后需要水车重新更新（重新放置或方块更新）才会生效",
                    "Rotation speed (RPM) generated by the wheel when water flows. Takes effect after the wheel updates (re-place it or trigger a block update)")
                    .defineInRange("rotationSpeed", defaultRpm, 1, 256);
            stressMultiplier = builder.comment(
                    "提供应力的倍率，相对于 Create 原版大水车的应力容量（SU/RPM）。最终应力 = 原版大水车容量 × 倍率 × 转速",
                    "Stress capacity multiplier relative to Create's vanilla large water wheel (SU/RPM). Final stress = vanilla capacity x multiplier x RPM")
                    .defineInRange("stressMultiplier", defaultMultiplier, 0.0, 1000000.0);
            upgradeEnabled = builder.comment(
                    "是否允许手持" + itemZh + "右键原版大水车，将其原地升级为" + nameZh,
                    "Whether right-clicking a vanilla large water wheel with " + itemEn + " upgrades it in place to the " + nameEn)
                    .define("rightClickUpgrade", true);
            builder.pop();
            spec = builder.build();
        }

        public SimpleRegistry.Provider<Block, BlockStressValues.GeneratedRpm> rpmProvider(Block wheel) {
            return target -> {
                if (target == wheel) {
                    return new BlockStressValues.GeneratedRpm(rpm(), false);
                }
                return null;
            };
        }

        public int rpm() {
            if (!spec.isLoaded()) {
                return defaultRpm;
            }
            return rpm.get();
        }

        public double stressMultiplier() {
            if (!spec.isLoaded()) {
                return defaultMultiplier;
            }
            return stressMultiplier.get();
        }

        public boolean upgradeEnabled() {
            if (!spec.isLoaded()) {
                return true;
            }
            return upgradeEnabled.get();
        }
    }
}
